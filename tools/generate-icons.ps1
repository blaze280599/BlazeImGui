# Regenerates src/BlazeImGui/Icons.g.cs (and the font) from a lucide-static release.
# Usage: powershell -File tools/generate-icons.ps1 [-Version 0.469.0]
# Afterwards rebuild; the font is embedded into BlazeImGui.dll.
param([string]$Version = "0.469.0")
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot
$fonts = Join-Path $root "src\BlazeImGui\Assets\Fonts"
$out = Join-Path $root "src\BlazeImGui\Icons.g.cs"
$base = "https://cdn.jsdelivr.net/npm/lucide-static@$Version"

Invoke-WebRequest "$base/font/lucide.ttf" -OutFile (Join-Path $fonts "lucide.ttf")
$css = (Invoke-WebRequest "$base/font/lucide.css" -UseBasicParsing).Content
$found = [regex]::Matches($css, '\.icon-([a-z0-9-]+):before \{ content: "\\([0-9a-f]+)"')
$codes = $found | ForEach-Object { [Convert]::ToInt32($_.Groups[2].Value, 16) } | Sort-Object

$sb = [Text.StringBuilder]::new()
[void]$sb.AppendLine("// <auto-generated> Lucide icon font codepoints (lucide-static $Version, ISC license).")
[void]$sb.AppendLine('// Browse icons by name at https://lucide.dev/icons - the constant is the icon name in PascalCase,')
[void]$sb.AppendLine('// e.g. "chevron-right" -> Icons.ChevronRight. Use inside any ImGui text: $"{Icons.Settings}  Settings".')
[void]$sb.AppendLine('// Regenerate with tools/generate-icons.ps1; do not edit by hand.')
[void]$sb.AppendLine('namespace BlazeImGui;'); [void]$sb.AppendLine('')
[void]$sb.AppendLine('public static class Icons'); [void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>First and last codepoint in the icon font; used to build the glyph range.</summary>')
[void]$sb.AppendLine(('    public const ushort RangeStart = 0x{0:X4}, RangeEnd = 0x{1:X4};' -f $codes[0], $codes[-1])); [void]$sb.AppendLine('')
$seen = @{}
foreach ($m in $found) {
    $name = (($m.Groups[1].Value -split '-') | Where-Object { $_ } | ForEach-Object { $_.Substring(0,1).ToUpper() + $_.Substring(1) }) -join ''
    if ($name -match '^\d') { $name = '_' + $name }
    if ($seen.ContainsKey($name)) { continue }
    $seen[$name] = 1
    [void]$sb.AppendLine(('    public const string {0} = "\u{1}";' -f $name, $m.Groups[2].Value.ToUpper()))
}
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($out, $sb.ToString())
"Wrote $($seen.Count) icons to $out"
